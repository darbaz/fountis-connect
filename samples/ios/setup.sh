#!/bin/sh
# Creates Sources/Config.local.swift (gitignored) from ../.sandbox-keys.local.json, or a placeholder if that file is missing.
set -e
cd "$(dirname "$0")"
python3 - <<'PY'
import json, os
keys = "../.sandbox-keys.local.json"
key, base = "pk_test_PASTE_YOUR_SANDBOX_KEY", "https://api.fountis.org/connect/v1"
if os.path.exists(keys):
    d = json.load(open(keys))
    key = d["apps"]["app_demo_ios"]["test_key"]
    base = d.get("api_base", base)
else:
    print("note: ../.sandbox-keys.local.json not found; wrote a placeholder key")
open("Sources/Config.local.swift", "w").write(f'''// Generated by setup.sh. Gitignored: never commit.
enum SampleConfig {{
    static let key = "{key}"
    static let apiBase = "{base}"
    static let partnerId = "ptn_demo"
    static let appId = "app_demo_ios"
}}
''')
print("wrote Sources/Config.local.swift")
PY
